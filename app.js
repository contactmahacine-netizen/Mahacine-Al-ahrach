    /* ----------------------------------------------------------
     * 1. ANIMATED PARTICLE BACKGROUND (Canvas)
     * ---------------------------------------------------------- */
    const canvas = document.getElementById('bg-canvas');
    const ctx = canvas.getContext('2d');

    let particles = [];
    let animFrameId;

    function resizeCanvas() {
        canvas.width = window.innerWidth;
        canvas.height = window.innerHeight;
    }

    resizeCanvas();
    window.addEventListener('resize', () => {
        resizeCanvas();
        initParticles();
    });

    class Particle {
        constructor() {
            this.reset(true);
        }

        reset(initial = false) {
            this.x = Math.random() * canvas.width;
            this.y = initial ? Math.random() * canvas.height : canvas.height + 10;
            this.radius = Math.random() * 2.5 + 0.5;
            this.speedX = (Math.random() - 0.5) * 0.5;
            this.speedY = -(Math.random() * 0.6 + 0.15);
            this.opacity = Math.random() * 0.6 + 0.15;
            this.opacityDrift = (Math.random() - 0.5) * 0.005;
            // Mix: ~30% red, ~70% white
            const roll = Math.random();
            if (roll < 0.30) {
                this.color = `rgba(230, 20, 20, ${this.opacity})`;
                this.isRed = true;
            } else {
                this.color = `rgba(255, 255, 255, ${this.opacity})`;
                this.isRed = false;
            }
        }

        update() {
            this.x += this.speedX;
            this.y += this.speedY;
            this.opacity += this.opacityDrift;
            if (this.opacity <= 0.05 || this.opacity >= 0.75) this.opacityDrift *= -1;

            // Update color with current opacity
            const alpha = Math.max(0.05, Math.min(this.opacity, 0.8));
            this.color = this.isRed
                ? `rgba(230, 20, 20, ${alpha})`
                : `rgba(255, 255, 255, ${alpha})`;

            // Reset when offscreen
            if (this.y < -10 || this.x < -10 || this.x > canvas.width + 10) {
                this.reset();
            }
        }

        draw() {
            ctx.beginPath();
            ctx.arc(this.x, this.y, this.radius, 0, Math.PI * 2);
            ctx.fillStyle = this.color;
            ctx.fill();
        }
    }

    function initParticles() {
        particles = [];
        const count = Math.floor((canvas.width * canvas.height) / 9000);
        for (let i = 0; i < count; i++) {
            particles.push(new Particle());
        }
    }

    function drawConnections() {
        const maxDist = 120;
        for (let i = 0; i < particles.length; i++) {
            for (let j = i + 1; j < particles.length; j++) {
                const dx = particles[i].x - particles[j].x;
                const dy = particles[i].y - particles[j].y;
                const dist = Math.sqrt(dx * dx + dy * dy);
                if (dist < maxDist) {
                    const alpha = (1 - dist / maxDist) * 0.12;
                    // Blend colors of connecting particles
                    const ci = particles[i].isRed, cj = particles[j].isRed;
                    let lineColor;
                    if (ci && cj)      lineColor = `rgba(230, 20, 20, ${alpha})`;
                    else if (!ci && !cj) lineColor = `rgba(255, 255, 255, ${alpha})`;
                    else               lineColor = `rgba(200, 100, 100, ${alpha})`;

                    ctx.beginPath();
                    ctx.moveTo(particles[i].x, particles[i].y);
                    ctx.lineTo(particles[j].x, particles[j].y);
                    ctx.strokeStyle = lineColor;
                    ctx.lineWidth = 0.6;
                    ctx.stroke();
                }
            }
        }
    }

    function animateParticles() {
        ctx.clearRect(0, 0, canvas.width, canvas.height);
        drawConnections();
        particles.forEach(p => { p.update(); p.draw(); });
        animFrameId = requestAnimationFrame(animateParticles);
    }

    initParticles();
    animateParticles();


